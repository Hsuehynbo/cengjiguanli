-- 创建数据库
CREATE DATABASE IF NOT EXISTS company_talk_system DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE company_talk_system;

-- 创建部门表
CREATE TABLE IF NOT EXISTS depts (
    id INT PRIMARY KEY AUTO_INCREMENT,
    dept_name VARCHAR(50) NOT NULL
);

-- 创建用户表
CREATE TABLE IF NOT EXISTS users (
    id INT PRIMARY KEY AUTO_INCREMENT,
    job_no VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL,
    dept_id INT,
    position VARCHAR(50) NOT NULL,
    superior_job_no VARCHAR(20),
    avatar VARCHAR(255),
    password VARCHAR(100) NOT NULL DEFAULT '123456',
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    is_key_personnel BOOLEAN NOT NULL DEFAULT FALSE,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (dept_id) REFERENCES depts(id)
);

-- 创建谈话记录表
CREATE TABLE IF NOT EXISTS talk_records (
    id INT PRIMARY KEY AUTO_INCREMENT,
    talker_job_no VARCHAR(20) NOT NULL,
    target_job_no VARCHAR(20) NOT NULL,
    talk_time DATETIME NOT NULL,
    location VARCHAR(100) NOT NULL,
    content TEXT NOT NULL,
    photo VARCHAR(255),
    talk_type VARCHAR(50),
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (talker_job_no) REFERENCES users(job_no),
    FOREIGN KEY (target_job_no) REFERENCES users(job_no)
);

-- 创建家访记录表
CREATE TABLE IF NOT EXISTS home_visits (
    id INT PRIMARY KEY AUTO_INCREMENT,
    target_job_no VARCHAR(20) NOT NULL,
    visit_time DATETIME NOT NULL,
    visit_type VARCHAR(50) NOT NULL,
    location VARCHAR(100) NOT NULL,
    content TEXT NOT NULL,
    photo VARCHAR(255),
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (target_job_no) REFERENCES users(job_no)
);

-- 创建层级历史表
CREATE TABLE IF NOT EXISTS hierarchy_history (
    id INT PRIMARY KEY AUTO_INCREMENT,
    target_job_no VARCHAR(20) NOT NULL,
    start_date DATETIME NOT NULL,
    end_date DATETIME,
    unit_name VARCHAR(100),
    manager_job_no VARCHAR(20),
    manager_name VARCHAR(50),
    FOREIGN KEY (target_job_no) REFERENCES users(job_no)
);

-- 创建违规记录表
CREATE TABLE IF NOT EXISTS violation_records (
    id INT PRIMARY KEY AUTO_INCREMENT,
    target_job_no VARCHAR(20) NOT NULL,
    violation_time DATETIME NOT NULL,
    reason TEXT NOT NULL,
    punishment VARCHAR(255) NOT NULL,
    created_by VARCHAR(20),
    FOREIGN KEY (target_job_no) REFERENCES users(job_no)
);

